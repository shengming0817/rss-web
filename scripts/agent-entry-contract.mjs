import assert from 'node:assert/strict'
import { mkdtemp, readFile, writeFile, rm, mkdir } from 'node:fs/promises'
import { homedir, tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import process from 'node:process'
import { compile } from 'json-schema-to-typescript'
import { format, resolveConfig } from 'prettier'
import { executeBounded } from '../e2e/identity/process.mjs'

const root = fileURLToPath(new URL('../', import.meta.url)),
  contract = join(root, 'contracts/agent-entry/contract.json'),
  source = JSON.parse(await readFile(join(root, 'contracts/agent-entry/source.json'), 'utf8')),
  generated = join(root, 'apps/mdm/src/agent-entry.generated.ts'),
  refresh = process.argv.includes('--refresh'),
  checkRust = process.argv.includes('--check-rust'),
  check = process.argv.includes('--check') || checkRust

assert.match(source.revision, /^[a-f0-9]{40}$/)
assert.equal(source.repository, 'https://dev.azure.com/shengming0923/rss/_git/rss-mdm-agent')

async function probe() {
  const checkout = process.env.MDM_AGENT_ENTRY_SOURCE
  assert.ok(
    checkout,
    'Set MDM_AGENT_ENTRY_SOURCE to an Agent checkout containing the fixed revision',
  )
  const scratch = await mkdtemp(join(tmpdir(), 'rss-web-agent-entry-'))
  let terminate,
    interrupted = false
  const interrupt = () => {
    interrupted = true
    terminate?.()
  }
  const bounded = async (cmd, args, timeoutMs, env = process.env) => {
    if (interrupted) throw new Error('Agent contract probe interrupted')
    const result = await executeBounded(cmd, args, {
      cwd: scratch,
      timeoutMs,
      env,
      stdio: ['ignore', 'pipe', 'pipe'],
      onChild: (_child, stop) => {
        terminate = stop
      },
      onRelease: () => {
        terminate = undefined
      },
    })
    if (result.status !== 0 || result.timedOut || interrupted) {
      const diagnostic = result.stderr
        .split('\n')
        .filter((line) => /^(error:|Caused by:|  (failed|error|No such))/.test(line))
        .slice(0, 8)
        .join('\n')
        .replace(/https?:\/\/[^\s/]+@/g, 'https://[redacted]@')
      throw new Error(
        `${cmd} failed during Agent contract probe${diagnostic ? ': ' + diagnostic : ''}`,
      )
    }
    return result.stdout
  }
  process.on('SIGINT', interrupt)
  process.on('SIGTERM', interrupt)
  try {
    await mkdir(join(scratch, 'agent'))
    await mkdir(join(scratch, 'probe', 'src'), { recursive: true })
    await bounded(
      '/usr/bin/git',
      [
        '-C',
        resolve(checkout),
        'archive',
        '--format=tar',
        '-o',
        join(scratch, 'source.tar'),
        source.revision,
      ],
      60_000,
    )
    await bounded('tar', ['-xf', 'source.tar', '-C', 'agent'], 60_000)
    await writeFile(
      join(scratch, 'probe', 'Cargo.toml'),
      `[package]\nname = "rss-web-agent-entry-probe"\nversion = "0.0.0"\nedition = "2021"\n[workspace]\n[dependencies]\nexecution-contract = { path = "../agent/crates/execution-contract" }\nschemars = "=1.2.2"\nserde_json = "=1.0.151"\n`,
    )
    await writeFile(
      join(scratch, 'probe/src/main.rs'),
      await readFile(join(root, 'scripts/agent-entry-probe.rs')),
    )
    return JSON.parse(
      await bounded(
        'cargo',
        [
          '+1.96.0',
          'run',
          '--quiet',
          '--offline',
          '--manifest-path',
          join(scratch, 'probe/Cargo.toml'),
        ],
        600_000,
        {
          ...process.env,
          CARGO_TARGET_DIR: join(homedir(), '.cache/rss-web/agent-entry-contract'),
        },
      ),
    )
  } finally {
    process.off('SIGINT', interrupt)
    process.off('SIGTERM', interrupt)
    await rm(scratch, { recursive: true, force: true })
  }
}

if (refresh)
  await writeFile(
    contract,
    await format(JSON.stringify(await probe()), {
      ...(await resolveConfig(contract)),
      parser: 'json',
    }),
  )
const document = JSON.parse(await readFile(contract, 'utf8'))
if (checkRust)
  assert.deepEqual(await probe(), document, 'Agent Rust contract or canonical vectors drifted')
const types = await compile(document.schema, 'EntryIntent', {
  bannerComment:
    '// Generated by scripts/agent-entry-contract.mjs from the fixed Agent Rust contract.',
  unreachableDefinitions: true,
  maxItems: -1,
})
const binding = await format(
  `${types}\nexport const entryUriBytes = ${document.maxBytes} as const\nexport const entryNodes = ${JSON.stringify(document.nodes)} as const\n`,
  {
    ...(await resolveConfig(generated)),
    parser: 'typescript',
  },
)
if (check) assert.equal(await readFile(generated, 'utf8'), binding, 'Agent entry bindings drifted')
else await writeFile(generated, binding)
